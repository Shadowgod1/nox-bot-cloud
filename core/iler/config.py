"""Runtime configuration. All variables use the ILER_ prefix."""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict

VERSION = "0.4.4"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="ILER_", extra="ignore")

    database_url: str = "postgresql://iler:iler@postgres:5432/iler"
    # 32 random bytes, base64. Used for AES-GCM of stored secrets and to derive the session key.
    secret_key: str = ""
    evo_url: str = "http://evolution-api:8080"
    evo_api_key: str = ""
    evo_instance: str = "iler"
    # URL Evolution calls back on (inside the docker network).
    webhook_url: str = "http://iler-core:8000/internal/evolution/webhook"
    updater_url: str = "http://iler-updater:9000"
    updater_token: str = ""
    # One-time token for POST /api/setup/owner (generated by install.sh, shown in the setup link).
    setup_token: str = ""
    # Owner handed over by the Nox portal (cloud instances, written by iler-client.sh create): on start, while no
    # user exists, the owner is created with this e-mail, name and the portal's argon2id password hash, so the
    # client logs in with the cabinet password. Ignored once any user exists (iler.auth.preset_owner).
    owner_email: str = ""
    owner_name: str = ""
    owner_password_hash: str = ""
    # Company from the portal application: pre-fills the template field business_name of the bot setup.
    company: str = ""
    # Redis password (backups talk to redis with it).
    redis_password: str = ""
    # ILER's own LLM API keys, set by the ILER technician (deploy/set-llm-keys.sh); never editable in the UI
    openai_key: str = ""
    gemini_key: str = ""
    anthropic_key: str = ""
    # Optional per-provider API base URLs (empty = the provider's public API). Ignored in gateway mode.
    openai_base_url: str = ""
    gemini_base_url: str = ""
    anthropic_base_url: str = ""
    # LLM gateway mode (cloud and managed installs): every provider is reached through
    # <llm_gateway_url>/llm/<provider>/... with the install's virtual key instead of the ILER_*_KEY;
    # the gateway swaps in the real key and is the authority on coins. Empty URL = off.
    llm_gateway_url: str = ""
    llm_gateway_key: str = ""
    # Where the owner tops up coins (shown as the "Пополнить" link in the admin UI); empty = no link.
    topup_url: str = ""
    # ILER coins (iler.usage): monthly limit set by ILER (0 = no limit) and optional price overrides (JSON)
    monthly_coins: int = 0
    model_prices: str = ""
    tz: str = "Asia/Almaty"
    # Public address of a cloud instance behind the tunnel (https://client.example.kz); empty on a LAN.
    # An https:// address makes every auth cookie Secure.
    public_url: str = ""
    # Brand of the admin UI and of user-facing texts: "iler" (on-prem, default) or "nox" (cloud edition
    # run by Nox service). Unknown values fall back to "iler".
    brand: str = "iler"
    data_dir: str = "/data"
    disable_workers: bool = False
    llm_fake: bool = False


def gateway_mode() -> bool:
    """LLM gateway mode is on (ILER_LLM_GATEWAY_URL is set)."""
    return bool(get_settings().llm_gateway_url.strip())


def topup_url() -> str | None:
    """The coin top-up link for the admin UI; only http(s) URLs are passed on."""
    value = get_settings().topup_url.strip()
    return value if value.lower().startswith(("https://", "http://")) else None


def cookies_secure() -> bool:
    """Auth cookies get the Secure flag when the instance is served over https (cloud, behind the tunnel)."""
    return get_settings().public_url.strip().lower().startswith("https://")


BRANDS = ("iler", "nox")
# Product name shown to users, and the company name used in "contact ..." texts.
_BRAND_NAMES = {"iler": ("ILER", "ILER"), "nox": ("Nox", "Nox service")}


def brand() -> str:
    """Configured brand id (ILER_BRAND), normalised; anything unknown is the default "iler"."""
    value = get_settings().brand.strip().lower()
    return value if value in BRANDS else "iler"


def brand_name() -> str:
    """Product name for user-facing texts: "ILER" or "Nox"."""
    return _BRAND_NAMES[brand()][0]


def brand_company() -> str:
    """Company to contact in user-facing texts: "ILER" or "Nox service"."""
    return _BRAND_NAMES[brand()][1]


@lru_cache
def get_settings() -> Settings:
    return Settings()
